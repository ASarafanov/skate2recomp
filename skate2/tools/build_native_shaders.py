"""Compile the native renderer's HLSL shaders to SPIR-V and write the C++ header.

    python skate2/tools/build_native_shaders.py [--dxc path\\to\\dxc.exe]

The Vulkan backend of the native RHI takes prebuilt SPIR-V, so the generated
header (skate2/src/native/native_shaders_spirv.h) is committed and only needs
regenerating when a shader changes. It also embeds the HLSL source for the
Direct3D 12 backend, which compiles at runtime.

Needs a DXC build with SPIR-V code generation (the official
microsoft/DirectXShaderCompiler releases have it; the Windows SDK's dxc.exe
does not). By default it looks in tools/dxc/bin/x64/dxc.exe.
"""
import argparse
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHADER_DIR = os.path.join(ROOT, "skate2", "src", "native", "shaders")
OUT = os.path.join(ROOT, "skate2", "src", "native", "native_shaders_spirv.h")

# (file, entry point, profile, C++ name)
SHADERS = [
    ("world.hlsl", "vs_main", "vs_6_0", "kWorldVs"),
    ("world.hlsl", "ps_main", "ps_6_0", "kWorldPs"),
]
FLAGS = ["-spirv", "-fspv-target-env=vulkan1.1", "-O3"]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dxc", default=os.path.join(ROOT, "tools", "dxc", "bin", "x64", "dxc.exe"))
    args = parser.parse_args()
    version = subprocess.run([args.dxc, "--version"], capture_output=True, text=True).stdout.strip()
    out = [
        "// Generated by skate2/tools/build_native_shaders.py -- DO NOT EDIT.",
        "// SPIR-V compiled with DXC from skate2/src/native/shaders; regenerate after",
        "// changing a shader.",
        f"// Compiler: {version}",
        f"// Flags: {' '.join(FLAGS)}",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace skate2::native_shaders {",
        "",
    ]
    sources = {}
    for file, entry, profile, name in SHADERS:
        path = os.path.join(SHADER_DIR, file)
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, "out.spv")
            r = subprocess.run([args.dxc, "-T", profile, "-E", entry, *FLAGS, path, "-Fo", spv],
                               capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"{file}:{entry}: dxc failed\n{r.stdout}{r.stderr}")
            data = open(spv, "rb").read()
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        out.append(f"// {file} : {entry} ({len(data)} bytes)")
        out.append(f"inline constexpr uint32_t {name}[] = {{")
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
        out.append("};")
        out.append("")
        sources[file] = open(path, encoding="utf-8").read()
    for file, text in sources.items():
        var = "k" + "".join(p.capitalize() for p in os.path.splitext(file)[0].split("_")) + "Hlsl"
        out.append(f"// {file} source (Direct3D 12 compiles it at runtime).")
        out.append(f'inline constexpr char {var}[] = R"__hlsl__({text})__hlsl__";')
        out.append("")
    out.append("}  // namespace skate2::native_shaders")
    out.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
